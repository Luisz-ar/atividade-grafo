// ─────────────────────────────────────────────
//  6. Testar simetria da matriz
// ─────────────────────────────────────────────

void verificarSimetria(int matriz[TAM][TAM], const char *nomes[TAM]) {
    printf("  --- Verificar Simetria ---\n\n");

    int encontrou = 0;

    for (int i = 0; i < TAM; i++) {
        for (int j = i + 1; j < TAM; j++) {
            if (matriz[i][j] != matriz[j][i]) {
                printf("  [%s(%d)][%s(%d)] = %d\n", nomes[i], i, nomes[j], j, matriz[i][j]);
                printf("  [%s(%d)][%s(%d)] = %d\n", nomes[j], j, nomes[i], i, matriz[j][i]);
                printf("\n");
                encontrou = 1;
            }
        }
    }

    if (!encontrou)
        printf("  [OK] A matriz e simetrica.\n");
}