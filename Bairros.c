// ─────────────────────────────────────────────
//  2. Testar conexão direta
// ─────────────────────────────────────────────
void testarConexaoDireta(int matriz[TAM][TAM], const char *nomes[TAM]) {
    int x, y;

    printf("  --- Testar Conexao Direta ---\n");
    printf("  Indice X (0-%d): ", TAM - 1);
    scanf("%d", &x);
    printf("  Indice Y (0-%d): ", TAM - 1);
    scanf("%d", &y);

    if (x < 0 || x >= TAM || y < 0 || y >= TAM) {
        printf("\n  [!] Posicao invalida.\n");
        return;
    }

    printf("\n  Resultado: ");
    if (matriz[x][y] == 1)
        printf("%s  <-->  %s  [CONECTADOS]\n", nomes[x], nomes[y]);
    else
        printf("%s  <-X->  %s  [SEM CONEXAO DIRETA]\n", nomes[x], nomes[y]);
}

// ─────────────────────────────────────────────
//  3. Mostrar grafo completo
// ─────────────────────────────────────────────
void mostrarGrafo(int matriz[TAM][TAM], const char *nomes[TAM]) {
    printf("  --- Grafo Completo ---\n\n");

    for (int i = 0; i < TAM; i++) {
        printf("  [%2d] %-22s ->", i, nomes[i]);
        int primeiro = 1;
        for (int j = 0; j < TAM; j++) {
            if (matriz[i][j] == 1) {
                if (!primeiro) printf(",");
                printf(" %s", nomes[j]);
                primeiro = 0;
            }
        }
        if (primeiro) printf(" (sem conexoes)");
        printf("\n");
    }
}

// ─────────────────────────────────────────────
//  4. Conexões de um bairro específico
// ─────────────────────────────────────────────
void todasConexoesDeBairro(int matriz[TAM][TAM], const char *nomes[TAM]) {
    printf("  --- Conexoes de um Bairro ---\n");

    int bairro = buscarBairro(nomes);
    if (bairro == -1) return;

    printf("\n  Bairros conectados a \"%s\":\n", nomes[bairro]);

    int encontrou = 0;
    for (int j = 0; j < TAM; j++) {
        if (matriz[bairro][j]) {
            printf("    - %s\n", nomes[j]);
            encontrou = 1;
        }
    }

    if (!encontrou)
        printf("    (nenhuma conexao encontrada)\n");
}

// ─────────────────────────────────────────────
//  5. Adicionar conexão
// ─────────────────────────────────────────────
void adicionarConexao(int matriz[][TAM], const char *nomes[TAM]) {
    char bairro1[TAM], bairro2[TAM];
    int id1 = -1, id2 = -1;

    printf("  --- Adicionar Conexao ---\n");
    printf("  Bairro 1: ");
    scanf(" %74[^\n]", bairro1);
    printf("  Bairro 2: ");
    scanf(" %74[^\n]", bairro2);

    for (int i = 0; i < TAM; i++) {
        if (strcmp(bairro1, nomes[i]) == 0) id1 = i;
        if (strcmp(bairro2, nomes[i]) == 0) id2 = i;
    }

    if (id1 == -1) { printf("\n  [!] Bairro \"%s\" nao encontrado.\n", bairro1); return; }
    if (id2 == -1) { printf("\n  [!] Bairro \"%s\" nao encontrado.\n", bairro2); return; }

    if (matriz[id1][id2] == 1) {
        printf("\n  [!] \"%s\" e \"%s\" ja estao conectados.\n", bairro1, bairro2);
        return;
    }

    matriz[id1][id2] = 1;
    matriz[id2][id1] = 1;
    printf("\n  [OK] Conexao adicionada: %s  <-->  %s\n", nomes[id1], nomes[id2]);
}

